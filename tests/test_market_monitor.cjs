'use strict';
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const moduleText=fs.readFileSync(path.join(__dirname,'../site/market-monitor.js'),'utf8');
const indexText=fs.readFileSync(path.join(__dirname,'../site/index.html'),'utf8');
const context={window:{}};
vm.runInNewContext(moduleText,context);
const api=context.window.HQMarketMonitor;
assert.ok(api,'market monitor module must expose its API');
const data=api.defaultData();
assert.equal(data.updatedAt,'2026-11-24');
assert.equal(data.scenarios.reduce((sum,item)=>sum+item.probability,0),100,'scenario weights must total 100');
const html=api.renderDashboard(data,false);
assert.ok(html.includes('天津二手房仍处于调整期'));
assert.ok(html.includes('-0.5'));
assert.ok(html.includes('-5.3'));
assert.ok(html.includes('11,292'));
assert.ok(html.includes('未来底部情景概率'));
assert.ok(html.includes('反弹确认'));
assert.ok(html.includes('国家统计局'));
assert.ok(!html.includes('marketOpenObservation'),'read-only dashboard must not expose edit action');
const editable=api.renderDashboard(data,true);
assert.ok(editable.includes('data-action="marketOpenObservation"'),'unlocked dashboard must expose observation entry');
data.observations.push({id:'M1',period:'2026-11',label:'测试指标',value:'12',unit:'套',source:'测试来源',url:'https://example.com/source',note:'<script>alert(1)</script>'});
const withObservation=api.renderDashboard(data,true);
assert.ok(withObservation.includes('测试指标'));
assert.ok(withObservation.includes('&lt;script&gt;'));
assert.ok(!withObservation.includes('<script>alert(1)</script>'));
const normalized=api.normalize({observations:[{id:'M2',period:'2026-12',label:'保留记录'}]});
assert.equal(normalized.observations[0].id,'M2','normalization must preserve user observations');
assert.equal(api.renderTabs('records').includes('aria-selected="true"'),true);
assert.ok(indexText.includes('<script src="/market-monitor.js"></script>'),'market module must load before the app');
assert.ok(indexText.includes('state.marketMonitor'),'market data must be part of persisted app state');
assert.ok(indexText.includes('marketSaveObservation'),'manual observations must be saved through the app');
assert.ok(indexText.includes('function renderListingChanges(){'),'existing listing event log must remain available');
console.log('PASS market monitor: source-backed indicators, bottom scenarios, responsive view hooks and persisted observations');
